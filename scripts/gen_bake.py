#!/usr/bin/env python3
"""Generate infra/bake/mocks.hcl — one docker-bake target per mock directory.

Every infra/docker/<mock>/ that holds a Dockerfile.vuln gets a vuln/patched matrix
target tagged noctis/<mock>:<variant> (the same images `task build` produces with
podman). Mocks built FROM noctis/py-mock-base get that base wired in through
`contexts`, so `docker buildx bake -f infra/bake/mocks.hcl` builds it first.

The file is generated: never edit it by hand, and on a merge conflict just re-run
the generator. Run via `task bake-gen` (from infra/):

    python3 scripts/gen_bake.py            # rewrite infra/bake/mocks.hcl
    python3 scripts/gen_bake.py --check    # exit 1 if it is out of date
"""
import os
import sys

REPO_ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
DOCKER_DIR = os.path.join(REPO_ROOT, "infra", "docker")
OUT = os.path.join(REPO_ROOT, "infra", "bake", "mocks.hcl")
BASE_IMAGE = "noctis/py-mock-base"
BASE_TARGET = "py-mock-base"
BASE_DIR = "_base/python-mock"


def mocks() -> list[tuple[str, bool]]:
    out = []
    for name in sorted(os.listdir(DOCKER_DIR)):
        vuln = os.path.join(DOCKER_DIR, name, "Dockerfile.vuln")
        if name.startswith("_") or not os.path.isfile(vuln):
            continue
        with open(vuln, encoding="utf-8") as fh:
            uses_base = any(
                line.strip().startswith(f"FROM {BASE_IMAGE}") for line in fh
            )
        out.append((name, uses_base))
    return out


def render() -> str:
    items = mocks()
    lines = [
        "# Generated by scripts/gen_bake.py — do not edit by hand.",
        "# Regenerate with: task bake-gen   (on a merge conflict, just regenerate)",
        "",
        'group "default" {',
        "  targets = [",
    ]
    lines += [f'    "{name}",' for name, _ in items]
    lines += [
        "  ]",
        "}",
        "",
        f'target "{BASE_TARGET}" {{',
        f'  context    = "../docker/{BASE_DIR}"',
        '  dockerfile = "Dockerfile"',
        f'  tags       = ["{BASE_IMAGE}:latest"]',
        "}",
    ]
    for name, uses_base in items:
        lines += [
            "",
            f'target "{name}" {{',
            f'  name       = "{name}-${{variant}}"',
            '  matrix     = { variant = ["vuln", "patched"] }',
            f'  context    = "../docker/{name}"',
            '  dockerfile = "Dockerfile.${variant}"',
            f'  tags       = ["noctis/{name}:${{variant}}"]',
        ]
        if uses_base:
            lines.append(f'  contexts   = {{ "{BASE_IMAGE}" = "target:{BASE_TARGET}" }}')
        lines.append("}")
    return "\n".join(lines) + "\n"


def main() -> int:
    content = render()
    if "--check" in sys.argv:
        current = open(OUT, encoding="utf-8").read() if os.path.isfile(OUT) else ""
        if current != content:
            print("gen_bake: infra/bake/mocks.hcl is out of date — run `task bake-gen`", file=sys.stderr)
            return 1
        print("gen_bake: infra/bake/mocks.hcl in sync.")
        return 0
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write(content)
    print(f"gen_bake: wrote {os.path.relpath(OUT, REPO_ROOT)} ({len(mocks())} mocks).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
